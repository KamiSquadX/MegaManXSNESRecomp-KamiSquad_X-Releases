#!/usr/bin/env python3
"""Build KSX Zero's pause-menu skill icons.

    python tools/saber/build_ksx_zero_icons.py \
        --x4 <Mega Man X4 weapon-menu screenshot> --x8 <X8 16-bit project>

Ryuenjin, Rakuhouha, Kuuenbu and Hyouretsuzan come from Mega Man X4's
weapon menu (a 2356x1771 capture of its 320x240 screen); Raikousen,
Youdantotsu, Juuhazan and Rekkyoudan from X8 16-bit's Zero pause menu
(Zero_mod/HUD/Pause/selectable_weapon_0N.png). Each icon's art is cut from
its own frame and background and fitted to the 12x12 inside of X1's icon
frame, which the renderer draws around it.

Writes assets/ksx-zero/icons/*.png and src/saber/mmx_saber_ksx_icons.h.
Only Pillow is needed; the outputs are tracked.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
OUT_DIR = ROOT / "assets" / "ksx-zero" / "icons"
HEADER = ROOT / "src" / "saber" / "mmx_saber_ksx_icons.h"
SIZE = 12

# MmxKsxSkill order.
SKILLS = ["ryuenjin", "rakuhouha", "raikousen", "kuuenbu", "hyouretsuzan",
          "youdantotsu", "juuhazan", "rekkyoudan"]
# X4: the outer top-left corner of each icon frame in the capture.
X4_ICONS = {"rakuhouha": (236, 189), "ryuenjin": (236, 549),
            "kuuenbu": (1195, 189), "hyouretsuzan": (236, 729)}
X4_PITCH = 7.3625  # capture pixels per X4 pixel
# X8 16-bit's selectable_weapon_0N (sunflower .. rooster order).
X8_ICONS = {"juuhazan": 2, "raikousen": 4, "youdantotsu": 5, "rekkyoudan": 6}


def sample(capture: Image.Image, ox: int, oy: int, i: int, j: int):
    """Median of the 3x3 capture pixels at X4 pixel (i, j)'s centre."""
    cx = ox + (i + 0.5) * X4_PITCH
    cy = oy + (j + 0.5) * X4_PITCH
    s = sorted((capture.getpixel((int(cx) + dx, int(cy) + dy))
                for dx in (-1, 0, 1) for dy in (-1, 0, 1)), key=sum)
    return s[4]


def x4_icon(capture: Image.Image, ox: int, oy: int) -> Image.Image:
    # The frame is 2 px of teal around a 16x16 inside; the inside's grey
    # background is measured on its outermost ring.
    ring = sorted((sample(capture, ox, oy, i, j) for i in range(2, 18)
                   for j in range(2, 18) if i in (2, 17) or j in (2, 17)), key=sum)
    bg = ring[len(ring) // 2]
    art = Image.new("RGBA", (16, 16))
    for j in range(16):
        for i in range(16):
            c = sample(capture, ox, oy, i + 2, j + 2)
            near = sum(abs(c[k] - bg[k]) for k in range(3)) < 30
            art.putpixel((i, j), (0, 0, 0, 0) if near else c[:3] + (255,))
    x0, y0, x1, y1 = art.getbbox()
    side = max(x1 - x0, y1 - y0)
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    box = (cx - side / 2, cy - side / 2)
    out = Image.new("RGBA", (SIZE, SIZE))
    step = side / SIZE
    # Area-average onto 12x12; a cell is art when most of it is.
    for j in range(SIZE):
        for i in range(SIZE):
            fx0, fy0 = box[0] + i * step, box[1] + j * step
            acc, art_area, total = [0, 0, 0], 0.0, 0.0
            for y in range(16):
                for x in range(16):
                    w = max(0.0, min(fx0 + step, x + 1) - max(fx0, x))
                    h = max(0.0, min(fy0 + step, y + 1) - max(fy0, y))
                    if w * h <= 0:
                        continue
                    total += w * h
                    c = art.getpixel((x, y))
                    if c[3]:
                        art_area += w * h
                        acc = [acc[k] + c[k] * w * h for k in range(3)]
            if total and art_area / total >= 0.45:
                out.putpixel((i, j), tuple(int(v / art_area) for v in acc) + (255,))
    return out


def x8_icon(x8: Path, n: int) -> Image.Image:
    path = x8 / "Zero_mod" / "HUD" / "Pause" / f"selectable_weapon_{n:02d}.png"
    inner = Image.open(path).convert("RGB").crop((2, 2, 14, 14))
    out = Image.new("RGBA", (SIZE, SIZE))
    for y in range(SIZE):
        for x in range(SIZE):
            c = inner.getpixel((x, y))
            out.putpixel((x, y), (0, 0, 0, 0) if max(c) < 40 else c + (255,))
    return out


def bgr555(c) -> int:
    if c[3] < 128:
        return 0x8000
    return (c[0] >> 3) | ((c[1] >> 3) << 5) | ((c[2] >> 3) << 10)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--x4", type=Path, required=True)
    parser.add_argument("--x8", type=Path, required=True)
    args = parser.parse_args()
    capture = Image.open(args.x4).convert("RGB")
    icons = {}
    for name, (ox, oy) in X4_ICONS.items():
        icons[name] = x4_icon(capture, ox, oy)
    for name, n in X8_ICONS.items():
        icons[name] = x8_icon(args.x8, n)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    lines = ["/* Generated by tools/saber/build_ksx_zero_icons.py. */",
             "#pragma once", "#include <stdint.h>", "",
             "/* KSX Zero's 12x12 pause-menu icons, MmxKsxSkill order, BGR555;",
             " * 0x8000 is transparent. */",
             "static const uint16_t kMmxSaberKsxIcons[8][144] = {"]
    for name in SKILLS:
        icon = icons[name]
        icon.save(OUT_DIR / f"{name}.png", optimize=True)
        words = [bgr555(icon.getpixel((x, y))) for y in range(SIZE) for x in range(SIZE)]
        lines.append(f"  /* {name} */ {{")
        for row in range(SIZE):
            chunk = words[row * SIZE:(row + 1) * SIZE]
            lines.append("    " + ", ".join(f"0x{w:04x}" for w in chunk) + ",")
        lines.append("  },")
    lines.append("};")
    HEADER.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
